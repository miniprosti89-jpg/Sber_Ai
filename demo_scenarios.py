def match_scenario(text: str) -> Optional[dict]:
    """Возвращает наиболее подходящий сценарий по ключевым словам."""
    if not text:
        return None
    text = text.lower()
    best, best_score = None, 0
    for s in SCENARIOS:
        score = sum(1 for t in s["triggers"] if t in text)
        if score > best_score:
            best, best_score = s, score
    return best


def next_question(items: list) -> str:
    """Следующий уточняющий вопрос из сценария (fallback вместо LLM)."""
    all_text = " ".join((it.get("complaint") or "").lower() for it in items)
    scenario = match_scenario(all_text)
    if not scenario:
        return (
            "Расскажите, пожалуйста, подробнее: когда начались симптомы, "
            "как они менялись и что вы уже принимали?"
        )
    idx = len(items) - 1
    qs = scenario["questions"]
    if 0 <= idx < len(qs):
        return qs[idx]
    return "Спасибо! Информации достаточно — нажмите «Завершить», чтобы сформировать протокол."


def soap_for(items: list) -> Optional[dict]:
    """SOAP-шаблон из сценария (если найден)."""
    all_text = " ".join((it.get("complaint") or "").lower() for it in items)
    scenario = match_scenario(all_text)
    return scenario["soap"] if scenario else None